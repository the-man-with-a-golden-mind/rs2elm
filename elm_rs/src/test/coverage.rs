fn touch<T: Elm + ElmEncode + ElmDecode + ?Sized>(module: &mut Module) {
    T::contribute(module);
    T::contribute_encoder(module);
    T::contribute_decoder(module);
}

fn assert_transparent<T: Elm + ElmEncode + ElmDecode>(
    inner_type: &str,
    encoder: &str,
    decoder: &str,
) {
    assert_eq!(T::elm_type(), inner_type);
    assert_eq!(T::elm_definition(), None);
    assert_eq!(T::encoder_type(), encoder);
    assert_eq!(T::encoder_definition(), None);
    assert_eq!(T::decoder_type(), decoder);
    assert_eq!(T::decoder_definition(), None);
}

