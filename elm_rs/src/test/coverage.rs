#[allow(unused_parens)]
#[derive(Elm, ElmEncode, ElmDecode)]
struct Wire<T: 'static> {
    paren: (T),
    items: &'static [T],
}

#[test]
fn parentheses_and_slices_round_trip() {
    let definition = Wire::<i32>::elm_definition().unwrap();
    assert!(definition.contains("paren : a"), "{definition}");
    assert!(definition.contains("items : List (a)"), "{definition}");
    let encoder = Wire::<i32>::encoder_type();
    let decoder = Wire::<i32>::decoder_type();
    let encoded = super::elm_text::<Wire<i32>>(&format!(
        r#"    Json.Encode.encode 0 ({encoder} {{ paren = 5, items = [ 3, 4 ] }})"#
    ));
    assert_eq!(encoded, r#"{"paren":5,"items":[3,4]}"#);
    let decoded = super::elm_text::<Wire<i32>>(&format!(
        r#"    case Json.Decode.decodeString {decoder} "{{\"paren\":5,\"items\":[3,4]}}" of
        Ok value ->
            Json.Encode.encode 0 ({encoder} value)
        Err err ->
            Json.Decode.errorToString err"#
    ));
    assert_eq!(decoded, r#"{"paren":5,"items":[3,4]}"#);
}

