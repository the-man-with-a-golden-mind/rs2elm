//! Assemble an Elm module from generated definitions.

use crate::{ElmDecode, ElmEncode, instrument};
use std::collections::{HashMap, HashSet};

/// Definitions collected by `Elm::contribute` and the codec `contribute_*` methods.
#[doc(hidden)]
pub struct Module {
    body: String,
    seen: HashSet<String>,
    constructors: HashMap<String, String>,
    error: Option<std::io::Error>,
}

impl Module {
    /// Empty module. `contribute_*` methods append definitions.
    pub fn new() -> Self {
        Self {
            body: String::new(),
            seen: HashSet::new(),
            constructors: HashMap::new(),
            error: None,
        }
    }

    /// Returns true the first time `key` is recorded. Later calls are cycles or duplicates.
    pub fn mark(&mut self, key: &str) -> bool {
        self.seen.insert(key.to_string())
    }

    /// Append one Elm definition, with a blank line after it.
    pub fn push_definition(&mut self, definition: &str) {
        push_definition(&mut self.body, definition);
    }

    /// Record an Elm constructor. A collision is kept and returned by [`Module::finish`].
    pub fn note_constructor(&mut self, constructor: &str, type_name: &str) {
        if self.error.is_some() {
            return;
        }
        if let Err(err) = note_constructor(&mut self.constructors, constructor, type_name) {
            self.error = Some(err);
        }
    }

    /// Render the module, or return a constructor collision recorded earlier.
    #[instrument(skip(self), err, fields(module = name))]
    pub fn finish(self, name: &str) -> std::io::Result<String> {
        if let Some(err) = self.error {
            return Err(err);
        }
        Ok(render_module(name, &self.body))
    }
}

/// Record an Elm constructor. The same type may be exported twice.
/// Two different types that share a constructor are an error, because Elm has one constructor namespace per module.
#[doc(hidden)]
pub fn note_constructor(
    seen: &mut HashMap<String, String>,
    constructor: &str,
    type_name: &str,
) -> std::io::Result<()> {
    if let Some(previous) = seen.insert(constructor.to_string(), type_name.to_string()) {
        if previous != type_name {
            return Err(std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                format!(
                    "Elm constructor `{constructor}` is generated for both `{previous}` and `{type_name}`. Rename one with #[rs2elm(rename = \"...\")]"
                ),
            ));
        }
    }
    Ok(())
}

/// Append one generated definition, with a blank line after it.
#[doc(hidden)]
pub fn push_definition(body: &mut String, definition: &str) {
    body.push_str(definition.trim_end());
    body.push_str("\n\n");
}

/// Turn generated Elm definitions into a module Elm can compile.
///
/// Imports are chosen from the body. `Http` is never imported. The `Result`
/// helpers are included only when a generated codec calls them.
#[doc(hidden)]
#[instrument(skip(body), fields(module = name, bytes = body.len()))]
pub fn render_module(name: &str, body: &str) -> String {
    let mut prelude: String = [
        (
            "resultEncoder",
            <Result<(), ()> as ElmEncode>::encoder_definition(),
        ),
        (
            "resultDecoder",
            <Result<(), ()> as ElmDecode>::decoder_definition(),
        ),
    ]
    .into_iter()
    .filter(|(needle, _)| mentions(body, needle))
    .filter_map(|(_, definition)| definition)
    .fold(String::new(), |mut prelude, definition| {
        prelude.push_str(&definition);
        prelude.push_str("\n\n");
        prelude
    });
    if mentions(body, "elmRsPairsMap") && !body.contains("elmRsPairsMap decoder") {
        prelude.push_str(crate::elm_decode::OBJECT_PAIRS_MAP);
        prelude.push('\n');
        prelude.push('\n');
    }

    let full = format!("{prelude}{body}");
    let imports: Vec<&str> = [
        ("Dict", "import Dict exposing (Dict)"),
        ("Json.Decode", "import Json.Decode"),
        ("Json.Encode", "import Json.Encode"),
        ("Url.Builder", "import Url.Builder"),
    ]
    .into_iter()
    .filter(|(needle, _)| mentions(&full, needle))
    .map(|(_, line)| line)
    .collect();
    let import_block = if imports.is_empty() {
        String::new()
    } else {
        format!("{}\n\n", imports.join("\n"))
    };

    let keyword = if has_port(&full) {
        "port module"
    } else {
        "module"
    };
    format!("\n-- generated by rs2elm\n\n\n{keyword} {name} exposing (..)\n\n{import_block}{full}")
}

fn has_port(source: &str) -> bool {
    source.lines().any(|line| line.starts_with("port "))
}

/// True when `ident` appears as a whole Elm identifier.
///
/// `Json.Decode` matches `Json.Decode.field` and does not match `Json.Decoder`.
fn mentions(source: &str, ident: &str) -> bool {
    let bytes = source.as_bytes();
    source.match_indices(ident).any(|(index, _)| {
        let before_ok = index == 0 || !is_ident_continue(bytes[index - 1]);
        let after = index + ident.len();
        let after_ok = after >= bytes.len() || !is_ident_continue(bytes[after]);
        before_ok && after_ok
    })
}

fn is_ident_continue(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_'
}

#[cfg(test)]
mod tests {
    use super::{Module, mentions, note_constructor};
    use std::collections::HashMap;

    #[test]
    fn mentions_whole_identifier() {
        assert!(mentions("import Json.Decode", "Json.Decode"));
        assert!(mentions("Json.Decode.field", "Json.Decode"));
        assert!(!mentions("Json.Decoder", "Json.Decode"));
        assert!(mentions("Dict String", "Dict"));
        assert!(!mentions("Dictionary", "Dict"));
        assert!(!mentions("resultEncoderExtra", "resultEncoder"));
        assert!(mentions("resultEncoder err ok", "resultEncoder"));
    }

    #[test]
    fn the_same_constructor_may_be_recorded_twice_for_one_type() {
        let mut seen = HashMap::new();
        note_constructor(&mut seen, "A", "T").unwrap();
        note_constructor(&mut seen, "A", "T").unwrap();

        let mut module = Module::new();
        module.note_constructor("A", "T");
        module.note_constructor("A", "T");
        let source = module.finish("Same").unwrap();
        assert!(source.contains("module Same exposing (..)"), "{source}");
        assert!(!source.contains("import "), "{source}");
    }

    #[test]
    fn a_constructor_collision_stops_further_notes() {
        let mut module = Module::new();
        module.note_constructor("A", "T");
        module.note_constructor("A", "U");
        module.note_constructor("B", "V");
        let message = module.finish("Clash").unwrap_err().to_string();
        assert!(
            message.contains("Elm constructor `A` is generated for both `T` and `U`"),
            "{message}"
        );
    }
}
